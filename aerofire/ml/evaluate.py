"""Evaluate persistence vs physics vs hybrid on the TEST missions only -> docs/ML_RESULTS.md.

    python -m aerofire.ml.evaluate

Hybrid uses the runtime rule (aerofire.ml.predictor): physics where the runtime would fall back.
Metrics per target and horizon: MAE, RMSE, P90 (overall / Ascent / Float); mission-level bootstrap
95 % CI (1000 resamples) of the MAE improvement physics -> hybrid; single-row latency; top-3
permutation importance. Decision rule (fixed before evaluation): the hybrid is the default display
for a (target, horizon) only if that CI excludes 0 in favour of the hybrid. The primary metric is
altitude at 30 s.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np
from sklearn.inspection import permutation_importance

from . import features as F
from .predictor import HybridPredictor
from .train import DATA, MODELS, NAME, load

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "ML_RESULTS.md"
B = 1000
PRIMARY = "z@30"


def metrics(err: np.ndarray) -> dict[str, float]:
    a = np.abs(err)
    return {"mae": float(a.mean()), "rmse": float(np.sqrt((err ** 2).mean())), "p90": float(np.percentile(a, 90))} if len(a) else {}


def bootstrap(abs_phys: np.ndarray, abs_hyb: np.ndarray, groups: np.ndarray, rng: np.random.Generator) -> tuple[float, float]:
    ids = np.unique(groups)
    idx = {g: np.flatnonzero(groups == g) for g in ids}
    sp = np.array([abs_phys[idx[g]].sum() for g in ids])
    sh = np.array([abs_hyb[idx[g]].sum() for g in ids])
    n = np.array([len(idx[g]) for g in ids])
    draws = rng.integers(0, len(ids), (B, len(ids)))
    diff = (sp[draws].sum(1) - sh[draws].sum(1)) / n[draws].sum(1)
    return float(np.percentile(diff, 2.5)), float(np.percentile(diff, 97.5))


def main(argv: list[str] | None = None) -> int:
    d = load()
    pred = HybridPredictor(MODELS, NAME)
    card = pred.card
    test = d["split_test"] == 1
    rng = np.random.default_rng(11)
    rows, decisions, ci_all = [], {}, {}
    fallback = {}
    latency = {}
    importances = {}
    for h in card["horizons_s"]:
        m = test & (d["h"] == h)
        X, truth, phys, pers, isf, groups = d["X"][m], d["truth"][m], d["phys"][m], d["persist"][m], d["is_float"][m], d["seed"][m]
        oor = np.array([bool(pred.out_of_range(x)) for x in X])
        fallback[h] = float(oor.mean())
        for k, tgt in enumerate(F.TARGETS):
            key = f"{tgt}@{h}"
            mdl = pred.models[key]
            corr = np.where(oor, 0.0, mdl.predict(X))
            e_pers, e_phys, e_hyb = truth[:, k] - pers[:, k], truth[:, k] - phys[:, k], truth[:, k] - (phys[:, k] + corr)
            lo, hi = bootstrap(np.abs(e_phys), np.abs(e_hyb), groups, rng)
            ci_all[key] = [lo, hi]
            decisions[key] = lo > 0.0
            for split, sel in (("overall", np.ones(len(X), bool)), ("ascent", isf == 0), ("float", isf == 1)):
                rows.append({"key": key, "split": split, "n": int(sel.sum()), "persistence": metrics(e_pers[sel]),
                             "physics": metrics(e_phys[sel]), "hybrid": metrics(e_hyb[sel])})
            t0 = time.perf_counter()
            for i in range(200):
                mdl.predict(X[i: i + 1])
            latency[key] = (time.perf_counter() - t0) / 200 * 1e3
            if key in ("z@30", "east@60", "north@60"):
                sub = slice(0, None, 20)
                pi = permutation_importance(mdl, X[sub], (truth[:, k] - phys[:, k])[sub], n_repeats=3, random_state=0,
                                            scoring="neg_mean_absolute_error")
                order = np.argsort(pi.importances_mean)[::-1][:3]
                importances[key] = [(F.FEATURES[i], float(pi.importances_mean[i])) for i in order]
    primary = decisions[PRIMARY]
    ev = {"test_missions": len(np.unique(d["seed"][test])), "rows_test": int(test.sum()), "ci95_mae_improvement_m": ci_all,
          "default_enabled": decisions, "primary": PRIMARY, "primary_decision": "hybrid default" if primary else "physics default",
          "fallback_rate_by_horizon": fallback, "latency_ms_single_row": latency, "permutation_top3": importances,
          "table": rows, "bootstrap_resamples": B}
    card["evaluation"] = ev
    (MODELS / f"{NAME}.json").write_text(json.dumps(card, indent=1), encoding="utf-8")
    DOC.write_text(render(card, ev), encoding="utf-8")
    print(f"primary {PRIMARY}: CI {ci_all[PRIMARY][0]:.2f}..{ci_all[PRIMARY][1]:.2f} m -> {ev['primary_decision']}; wrote {DOC}")
    return 0


def render(card: dict, ev: dict) -> str:
    f = lambda x: f"{x:.1f}"  # noqa: E731
    out = [
        "# Hybrid physics + ML trajectory forecast: results",
        "",
        "Generated by `python -m aerofire.ml.evaluate` on **test missions only** "
        f"(seeds {card['test_seeds'][0]}-{card['test_seeds'][1]}, {ev['test_missions']} missions, {ev['rows_test']} rows). "
        f"Training: seeds {card['train_seeds'][0]}-{card['train_seeds'][1]}, {card['rows_train']} rows, "
        f"sklearn {card['sklearn']}, data SHA-256 `{card['data_sha256'][:16]}…`.",
        "",
        "**Everything here is simulator data.** Truth differs from the ground's assumptions only through the",
        "per-mission variability in `config/mission.yaml` `truth_variability` (wind scale and direction offset,",
        "balloon Cd, gas superheat, payload mass error; all ASSUMPTIONS). The improvement says the model learned",
        "*those* simulated discrepancies. It is not evidence about real balloons or real forecast errors.",
        "",
        "- **Persistence**: position held at the current fused value.",
        "- **Physics**: deterministic mean path of the ground particle predictor (current climb rate up to the design",
        "  float altitude, float holds, forecast winds).",
        "- **Hybrid**: physics + HistGradientBoosting residual (truth − physics), with the runtime fallback to physics",
        f"  when a feature is outside its training range (fallback rate on test rows: "
        + ", ".join(f"{h} s {100 * r:.1f} %" for h, r in ev["fallback_rate_by_horizon"].items()) + ").",
        "",
        f"Decision rule (fixed before evaluation): hybrid is the default display for a target/horizon only if the",
        f"mission-bootstrap 95 % CI ({ev['bootstrap_resamples']} resamples) of the MAE improvement excludes 0.",
        f"Primary metric: altitude at 30 s → **{ev['primary_decision']}**.",
        "",
        "## Overall (test missions)",
        "",
        "| target @ horizon | persistence MAE | physics MAE | hybrid MAE | improvement 95 % CI (m) | hybrid default |",
        "|---|---|---|---|---|---|",
    ]
    for r in ev["table"]:
        if r["split"] != "overall":
            continue
        lo, hi = ev["ci95_mae_improvement_m"][r["key"]]
        out.append(f"| {r['key']} s | {f(r['persistence']['mae'])} | {f(r['physics']['mae'])} | {f(r['hybrid']['mae'])} | "
                   f"{lo:.2f} … {hi:.2f} | {'yes' if ev['default_enabled'][r['key']] else 'no (experimental)'} |")
    out += ["", "## By phase: MAE / RMSE / P90 (m)", "", "| target @ horizon | phase | n | persistence | physics | hybrid |", "|---|---|---|---|---|---|"]
    for r in ev["table"]:
        if r["split"] == "overall":
            continue
        g = lambda m: f"{m['mae']:.1f} / {m['rmse']:.1f} / {m['p90']:.1f}" if m else "-"  # noqa: E731
        out.append(f"| {r['key']} s | {r['split']} | {r['n']} | {g(r['persistence'])} | {g(r['physics'])} | {g(r['hybrid'])} |")
    out += ["", "## Model", ""]
    out.append("| model | chosen parameters | CV MAE (m) | latency, one row (ms) |")
    out.append("|---|---|---|---|")
    for k, m in card["models"].items():
        out.append(f"| {k} | {json.dumps(m['params'])} | {min(m['cv_mae_m'].values()):.1f} | {ev['latency_ms_single_row'][k]:.2f} |")
    out += ["", "Permutation importance, top 3 (increase in test MAE when shuffled, m):", ""]
    for k, imp in ev["permutation_top3"].items():
        out.append(f"- {k}: " + ", ".join(f"`{n}` {v:.1f}" for n, v in imp))
    out += ["", "## Limits", "",
            "- Trained and tested only on simulator missions from one recorded atmosphere snapshot; truth = forecast",
            "  except for the listed variability. Real forecast errors, real balloon behaviour and sensor faults are not represented.",
            "- Only nominal missions (no faults) in ASCENT and FLOAT. Descent, faults and blackouts were not trained;",
            "  the runtime uses physics there (PHASE_NOT_TRAINED / OUT_OF_RANGE).",
            "- Rows from the same mission are correlated; the CI resamples whole missions.",
            "- The data-generation simulator skips the gondola pendulum (IMU only; not a feature).", ""]
    return "\n".join(out)


if __name__ == "__main__":
    sys.exit(main())
